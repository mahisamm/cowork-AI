CREATE TABLE IF NOT EXISTS employees (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  title TEXT NOT NULL,
  department TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','hr','manager','employee')),
  manager_id INTEGER REFERENCES employees(id),
  joined_on DATE NOT NULL,
  password_hash TEXT NOT NULL,
  CHECK (manager_id <> id)
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  expires BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
CREATE TABLE IF NOT EXISTS attendance (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  day DATE NOT NULL,
  clock_in TIMESTAMPTZ NOT NULL,
  clock_out TIMESTAMPTZ,
  UNIQUE (employee_id, day),
  CHECK (clock_out >= clock_in)
);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_shift ON attendance(employee_id) WHERE clock_out IS NULL;
CREATE TABLE IF NOT EXISTS leave_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  type TEXT NOT NULL CHECK (type IN ('Annual','Sick','Personal')),
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  reason TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected')),
  submitted_at TIMESTAMPTZ NOT NULL,
  reviewed_at TIMESTAMPTZ,
  reviewer_id INTEGER REFERENCES employees(id),
  CHECK (end_date >= start_date)
);
CREATE INDEX IF NOT EXISTS leave_employee_dates ON leave_requests(employee_id, start_date, end_date);
CREATE TABLE IF NOT EXISTS data_imports (
  source_hash TEXT PRIMARY KEY,
  imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  row_counts JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS personal_tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id INTEGER NOT NULL REFERENCES employees(id),
  title TEXT NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 120),
  notes TEXT NOT NULL DEFAULT '' CHECK (char_length(notes) <= 1000),
  due_on DATE,
  priority TEXT NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high')),
  completed BOOLEAN NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS personal_tasks_owner ON personal_tasks(employee_id);
